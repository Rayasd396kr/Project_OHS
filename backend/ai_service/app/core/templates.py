class PromptManager:
    PROMPTS = {
        "compliance_planning": PROMPT_COMPLIANCE_PLANNING,
        "sop_check": PROMPT_SOP_CHECK,
        "incident_analysis": PROMPT_INCIDENT_ANALYSIS,
        "prework_check": PROMPT_PREWORK_CHECK,
    }

    @classmethod
    def get_prompt(cls, scenario: str, context: str, query: str) -> str:
        # 如果傳入不認得的 scenario，預設使用 compliance_planning
        template = cls.PROMPTS.get(scenario, cls.PROMPTS["compliance_planning"])
        return template.format(context=context, query=query)